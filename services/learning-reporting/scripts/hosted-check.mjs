// Never echoes an argument: a pasted code or token must not reach the output.
export function parseArgs(argv) {
  const [mode, ...rest] = argv;
  if (!MODES.includes(mode)) throw new Stop('USAGE', { reason: 'mode' });
  const options = { mode };
  for (let index = 0; index < rest.length; index++) {
    const flag = rest[index];
    if (!Object.hasOwn(FLAGS, flag) || Object.hasOwn(options, flag)) throw new Stop('USAGE', { reason: 'flag' });
    if (FLAGS[flag] === 'flag') { options[flag] = true; continue; }
    const value = rest[++index];
    if (typeof value !== 'string' || value.startsWith('--')) throw new Stop('USAGE', { reason: 'value' });
    options[flag] = value;
  }
  const allowed = mode === 'verify-export' ? EXPORT_FLAGS : NETWORK_FLAGS;
  if (Object.keys(options).some(key => key !== 'mode' && !allowed.includes(key))) throw new Stop('USAGE', { reason: 'flag-for-mode' });
  const required = mode === 'verify-export' ? ['--ids', '--export', '--profile', '--out'] : ['--manifest', '--target', '--out'];
  if (required.some(key => !Object.hasOwn(options, key))) throw new Stop('USAGE', { reason: 'missing' });
  if (options['--await-retention'] && mode !== 'seed') throw new Stop('USAGE', { reason: 'flag-for-mode' });
  options.loopback = options['--loopback-tool-test'] === true;
  for (const key of ['--loopback-pace-ms', '--loopback-max-batches']) {
    if (!Object.hasOwn(options, key)) continue;
    if (!options.loopback) throw new Stop('LOOPBACK_ONLY_OPTION');
    if (!/^\d{1,6}$/.test(options[key])) throw new Stop('USAGE', { reason: 'number' });
    options[key] = Number(options[key]);
  }
  return options;
}

// An exact origin (no path, query, credentials or trailing slash). Remote targets are https
// with a DNS name and default port; loopback http is accepted only for the tool test.
export function originKind(value) {
  let url;
  try { url = new URL(value); } catch (error) { return null; }
  if (typeof value !== 'string' || url.origin !== value) return null;
  if (url.protocol === 'http:' && ['127.0.0.1', 'localhost'].includes(url.hostname) && url.port) return 'loopback';
  if (url.protocol === 'https:' && !url.port && /^[a-z0-9-]+(\.[a-z0-9-]+)+$/.test(url.hostname) && !/^[\d.]+$/.test(url.hostname)) return 'remote';
  return null;
}

async function loadManifest(options, now) {
  let bytes, manifest;
  try {
    bytes = await readFile(options['--manifest']);
    manifest = JSON.parse(bytes.toString('utf8'));
  } catch (error) { throw new Stop('MANIFEST', { reason: 'unreadable' }); }
  const keys = ['schemaVersion', 'target', 'gameOrigin', 'phase', 'expected', ...(options.mode === 'probe' ? [] : ['budget'])];
  if (!isRecord(manifest) || manifest.schemaVersion !== 1 || keys.some(key => !Object.hasOwn(manifest, key))
    || Object.keys(manifest).some(key => !['schemaVersion', 'target', 'gameOrigin', 'phase', 'expected', 'budget'].includes(key))) {
    throw new Stop(keys.includes('budget') && isRecord(manifest) && !Object.hasOwn(manifest, 'budget') ? 'BUDGET' : 'MANIFEST', { reason: 'keys' });
  }
  const target = originKind(manifest.target), game = originKind(manifest.gameOrigin);
  if (options.loopback && target !== 'loopback') throw new Stop('LOOPBACK_ONLY', { reason: 'target' });
  if (!options.loopback && target !== 'remote') throw new Stop('TARGET', { reason: target === 'loopback' ? 'loopback-needs-tool-test' : 'not-exact-https-origin' });
  if (options['--target'] !== manifest.target) throw new Stop('TARGET_MISMATCH');
  if (!game || (options.loopback && game !== 'loopback')) throw new Stop('MANIFEST', { reason: 'gameOrigin' });
  if (!PHASES.includes(manifest.phase)) throw new Stop('MANIFEST', { reason: 'phase' });
  // Uploads only while the deployed service is in controlled synthetic qualification:
  // never against the disabled service, and never once household data may exist.
  if (options.mode !== 'probe' && manifest.phase !== 'qualification') throw new Stop('PHASE', { phase: manifest.phase });
  const expected = manifest.expected;
  if (!isRecord(expected) || Object.keys(expected).sort().join() !== 'configSha256,contractSha256,sourceCommit,toolSha256,workerVersion'
    || !/^[0-9a-f]{40}$/.test(expected.sourceCommit) || !isUuid(expected.workerVersion)
    || ![expected.configSha256, expected.toolSha256, expected.contractSha256].every(value => /^[0-9a-f]{64}$/.test(value))) {
    throw new Stop('MANIFEST', { reason: 'expected' });
  }
  if (expected.toolSha256 !== sha(await readFile(SELF))) throw new Stop('DRIFT', { which: 'tool' });
  if (expected.contractSha256 !== sha(await readFile(CONTRACT))) throw new Stop('DRIFT', { which: 'contract' });
  const budget = options.mode === 'probe' ? null : checkBudget(manifest.budget, options.mode, now);
  return { manifest, manifestSha256: sha(bytes), budget };
}

// The owner's own reading of today's account-wide usage. Never assumed, never fetched here.
export function checkBudget(budget, mode, now) {
  const need = HEADROOM[mode];
  if (!isRecord(budget) || Object.keys(budget).sort().join() !== 'observedAtUtc,remaining,source,wholeAccount') throw new Stop('BUDGET', { reason: 'missing' });
  if (budget.source !== 'owner-dashboard' || budget.wholeAccount !== true) throw new Stop('BUDGET', { reason: 'source' });
  const at = typeof budget.observedAtUtc === 'string' && /Z$/.test(budget.observedAtUtc) ? Date.parse(budget.observedAtUtc) : NaN;
  if (!Number.isFinite(at) || at > now || now - at > ATTESTATION_MAX_AGE_MS) throw new Stop('BUDGET', { reason: 'stale' });
  // The free allowance resets at 00:00 UTC; a reading from another UTC day says nothing about today.
  if (new Date(at).toISOString().slice(0, 10) !== new Date(now).toISOString().slice(0, 10)) throw new Stop('BUDGET', { reason: 'other-utc-day' });
  const remaining = budget.remaining;
  if (!isRecord(remaining)) throw new Stop('BUDGET', { reason: 'remaining' });
  for (const [key, minimum] of Object.entries(need)) {
    if (!Number.isInteger(remaining[key]) || remaining[key] < minimum) throw new Stop('BUDGET', { reason: key, minimum });
  }
  return { observedAtUtc: budget.observedAtUtc, remaining: Object.fromEntries(Object.keys(need).map(key => [key, remaining[key]])), required: need };
}

async function outputDir(path) {
  const out = resolve(path), rel = relative(REPO, out);
  // Outside the repository, or under its ignored output/ tree: never beside tracked source.
  const inside = rel === '' || (!rel.startsWith('..') && !isAbsolute(rel));
  if (inside && rel !== 'output' && !rel.startsWith(`output${sep}`)) throw new Stop('OUT_PATH');
  await mkdir(out, { recursive: true, mode: 0o700 });
  return out;
}

// ---- Requests ----

function typeClass(value) {
  const type = String(value ?? '').toLowerCase();
  if (/^application\/json\b/.test(type)) return 'json';
  if (/^text\/html\b/.test(type)) return 'html';
  return type ? 'other' : 'none';
}
function redirectClass(target, location) {
  try {
    const url = new URL(location ?? '', target);
    if (url.protocol === 'https:' && url.hostname.endsWith('.cloudflareaccess.com')) return 'access-login';
    return url.origin === target ? 'same-origin' : 'other';
  } catch (error) { return 'invalid'; }
}
async function readCapped(response, max) {
  if (!response.body) return '';
  const reader = response.body.getReader(), chunks = [];
  let total = 0;
  try {
    for (;;) {
      const { done, value } = await reader.read();
      if (done) break;
      total += value.byteLength;
      if (total > max) { await reader.cancel().catch(() => {}); return null; }
      chunks.push(value);
    }
  } catch (error) { throw new Stop('NETWORK', { reason: 'body' }); }
  return Buffer.concat(chunks).toString('utf8');
}

// One request to a fixed path of the exact target. No redirect is followed and nothing is
// retried. A network failure reports only its class, never the error message or cause.
async function request(ctx, kind, method, path, { headers = {}, body } = {}) {
  if (!PATHS.has(path)) throw new Stop('PATH');
  if (ctx.requests >= ctx.maxRequests) throw new Stop('REQUEST_CAP', { cap: ctx.maxRequests });
  const wait = (ctx.last[kind] ?? -Infinity) + (ctx.paceMs ?? PACE_MS[kind]) - Date.now();
  if (wait > 0) await sleep(wait);
  ctx.last[kind] = Date.now();
  ctx.requests++;
  let response;
  try {
    response = await fetch(`${ctx.target}${path}`, { method, headers, body, redirect: 'manual', signal: AbortSignal.timeout(LIMITS.timeoutMs) });
  } catch (error) {
    throw new Stop('NETWORK', { path, reason: error?.name === 'TimeoutError' ? 'timeout' : 'network' });
  }
  const answer = { status: response.status, type: typeClass(response.headers.get('content-type')), cors: response.headers.has('access-control-allow-origin') };
  if (response.status >= 300 && response.status < 400) {
    await response.body?.cancel().catch(() => {});
    return { ...answer, redirect: redirectClass(ctx.target, response.headers.get('location')), data: null };
  }
  const text = await readCapped(response, LIMITS.responseBytes);
  let data = null;
  if (answer.type === 'json' && text) { try { data = JSON.parse(text); } catch (error) { data = null; } }
  return { ...answer, data };
}

// Which layer answered: the Access edge (login redirect or its own refusal page) or the
// Worker (its JSON error). Locations and bodies are classified, never reported.
export function layer(answer) {
  if (answer.redirect) return answer.redirect === 'access-login' ? 'edge:access-login' : `redirect:${answer.redirect}`;
  if (answer.type === 'json' && isRecord(answer.data) && typeof answer.data.error === 'string') return `worker:${word(answer.data.error)}`;
  if ((answer.status === 401 || answer.status === 403) && answer.type !== 'json') return 'edge:refusal';
  return `other:${answer.status}`;
}
const unexpected = (step, answer) => new Stop('UNEXPECTED', { step, status: answer.status, layer: layer(answer) });

// ---- Probe ----

async function probe(ctx) {
  for (const item of PROBES) {
    const headers = item.forged ? { 'Cf-Access-Jwt-Assertion': FORGED_JWT } : {};
    if (item.path === '/api/confirm') Object.assign(headers, { 'Content-Type': 'application/json', Origin: ctx.target });
    const answer = await request(ctx, 'probe', item.method, item.path, { headers, body: item.path === '/api/confirm' ? '{}' : undefined });
    const where = layer(answer);
    const row = { method: item.method, path: item.path, forged: item.forged, status: answer.status, layer: where, cors: answer.cors };
    ctx.steps.push(row);
    const ok = item.kind === 'protected'
      ? (answer.status < 200 || answer.status >= 300) && ['edge:access-login', 'edge:refusal', 'worker:unauthorized'].includes(where)
      : !answer.cors && (ctx.phase === 'disabled' ? answer.status === 503 && where === 'worker:disabled' : answer.status === 403 && where === 'worker:origin');
    if (!ok) throw new Stop('UNEXPECTED', { step: `${item.method} ${item.path}`, status: answer.status, layer: where });
  }
}

// ---- Synthetic events (the #199 contract, validated before sending) ----

function makeEvent(ctx, dev, profileId, game, kind, fields, { at = Date.now(), seq = ++dev.seq, question = randomUUID() } = {}) {
  if (++ctx.generated > LIMITS.maxEvents) throw new Stop('EVENT_CAP');
  const event = {
    schemaVersion: 1, eventId: randomUUID(), deviceId: dev.deviceId, epochId: dev.epochId, seq, profileId, game,
    gameVersion: GAME_VERSIONS[game], recordedAt: new Date(at).toISOString(), kind, questionInstanceId: question, ...fields,
  };
  if (!validateEvent(event)) throw new Stop('GENERATED_EVENT_INVALID');
  return event;
}
const FACT = Object.freeze({ factId: 'add:7:6', family: CATALOG.facts['add:7:6'] });
const FAMILY = Object.freeze({ familyId: 'score-total-ch8', ...CATALOG.football['score-total-ch8'] });
function factsQuestion(ctx, dev, profileId, at) {
  const question = randomUUID();
  return [
    makeEvent(ctx, dev, profileId, 'facts', 'attempt', { ...FACT, number: 1, correct: true, helped: false }, { at, question }),
    makeEvent(ctx, dev, profileId, 'facts', 'resolution', { ...FACT, outcome: 'first-correct', eligibleCheck: true, timingMs: null, helped: false }, { at, question }),
  ];
}
function footballQuestion(ctx, dev, profileId, at) {
  const question = randomUUID();
  return [
    makeEvent(ctx, dev, profileId, 'football', 'attempt', { ...FAMILY, number: 1, correct: true, support: 'initial' }, { at, question }),
    makeEvent(ctx, dev, profileId, 'football', 'resolution', { ...FAMILY, resolution: 'firstTryCorrect' }, { at, question }),
  ];
}
const leftEvent = (ctx, dev, profileId, options) => makeEvent(ctx, dev, profileId, 'facts', 'leftUnfinished', { ...FACT }, options);

// The retained growth corpus (fixture-budget growth_assumptions): 1,800 two-event
// questions alternating between devices X and Y; every sixth question belongs to the cold
// profile B, which only X carries. recordedAt is spread over the last 29 days so the whole
// corpus falls in the default 30-day report range.
export function buildCorpus(ctx, { X, Y, A, B, now }) {
  const questions = LIMITS.corpusEvents / 2, start = now - LIMITS.corpusSpanMs, out = { X: [], Y: [] };
  for (let q = 0; q < questions; q++) {
    const label = q % 2 ? 'X' : 'Y', dev = label === 'X' ? X : Y, profile = q % 6 === 5 ? B : A;
    const at = start + Math.floor((q * LIMITS.corpusSpanMs) / questions);
    out[label].push(...((q + Math.floor(q / 6)) % 2 ? factsQuestion(ctx, dev, profile, at) : footballQuestion(ctx, dev, profile, at)));
  }
  const all = [...out.X, ...out.Y];
  const ids = new Set(all.map(event => event.eventId));
  if (all.length !== LIMITS.corpusEvents || ids.size !== all.length
    || all.filter(event => event.profileId === A).length !== LIMITS.hotEvents || all.filter(event => event.profileId === B).length !== LIMITS.coldEvents
    || out.Y.some(event => event.profileId !== A)) throw new Stop('CORPUS_ALLOCATION');
  return out;
}
const chunks = events => Array.from({ length: Math.ceil(events.length / LIMITS.batch) }, (_, i) => events.slice(i * LIMITS.batch, (i + 1) * LIMITS.batch));

// ---- Device API ----

const deviceHeaders = (ctx, token) => ({ 'Content-Type': 'application/json', Origin: ctx.gameOrigin, ...(token ? { Authorization: `Bearer ${token}` } : {}) });
function statusOf(dev, highestSeq = dev.seq) {
  const status = { schemaVersion: 1, deviceId: dev.deviceId, epochId: dev.epochId, highestSeq, droppedLocal: 0, writeFailures: 0 };
  if (!validateStatus(status)) throw new Stop('GENERATED_STATUS_INVALID');
  return status;
}

async function enroll(ctx, code, label) {
  const answer = await request(ctx, 'enroll', 'POST', '/v1/enroll', { headers: deviceHeaders(ctx), body: JSON.stringify({ code }) });
  const data = answer.data;
  if (answer.status !== 200 || !isRecord(data) || data.schemaVersion !== 1 || typeof data.token !== 'string' || !TOKEN.test(data.token)
    || !isUuid(data.deviceId) || !Array.isArray(data.profileIds) || !data.profileIds.length || !data.profileIds.every(isUuid)) throw unexpected(`enroll-${label}`, answer);
  ctx.secrets.add(data.token);
  ctx.steps.push({ step: `enroll-${label}`, status: 200, profiles: data.profileIds.length });
  return { label, deviceId: data.deviceId, profileIds: data.profileIds, token: data.token, epochId: randomUUID(), seq: 0 };
}

async function sync(ctx, dev, events, { status = statusOf(dev), token = dev.token } = {}) {
  const body = JSON.stringify({ schemaVersion: 1, status, events });
  if (events.length > LIMITS.batch || Buffer.byteLength(body) > LIMITS.bodyBytes) throw new Stop('BATCH_BOUNDS');
  return request(ctx, 'sync', 'POST', '/v1/sync', { headers: deviceHeaders(ctx, token), body });
}

// Recoverable ID manifest: append-only JSON lines of IDs, seq, profile slot, game and the
// Worker's per-event outcome. Never a payload, code or token.
async function note(ctx, record) {
  await appendFile(ctx.idsFile, `${guard(ctx, JSON.stringify(record))}\n`, { mode: 0o600 });
}
const slotOf = (ctx, profileId) => Object.entries(ctx.profiles).find(([, id]) => id === profileId)?.[0] ?? 'unassigned';
async function noteDevice(ctx, dev, labels) {
  labels.forEach((label, index) => { ctx.profiles[label] = dev.profileIds[index]; });
  await note(ctx, { kind: 'device', label: dev.label, deviceId: dev.deviceId, profiles: Object.fromEntries(labels.map((label, i) => [label, dev.profileIds[i]])) });
}

// Sends one batch and requires exactly the expected per-event outcomes, in order, for
// exactly these event IDs. The batch is recorded as sent before the request, so a stop
// (including a timeout after commit) leaves it listed as unacknowledged.
async function step(ctx, name, dev, events, expected, options) {
  await note(ctx, { kind: 'sent', step: name, device: dev.label, events: events.map(event => ({
    eventId: event.eventId, epochId: event.epochId, seq: event.seq, profile: slotOf(ctx, event.profileId), game: event.game })) });
  const answer = await sync(ctx, dev, events, options);
  const results = answer.data?.results;
  const ok = answer.status === 200 && answer.data?.schemaVersion === 1 && Array.isArray(results) && results.length === events.length
    && results.every((item, i) => isRecord(item) && item.eventId === events[i].eventId && item.outcome === expected[i]);
  if (!ok) throw new Stop('UNEXPECTED', { step: name, status: answer.status, layer: layer(answer), outcomes: tally(results) });
  await note(ctx, { kind: 'ack', step: name, results: results.map(item => ({ eventId: item.eventId, outcome: item.outcome })) });
  for (const outcome of expected) ctx.outcomes[outcome] = (ctx.outcomes[outcome] ?? 0) + 1;
  for (const event of events) ctx.ids.add(event.eventId);
  ctx.steps.push({ step: name, status: 200, outcomes: tally(expected) });
}
async function expectError(ctx, name, answer, status, error) {
  if (answer.status !== status || answer.data?.error !== error) throw unexpected(name, answer);
  ctx.steps.push({ step: name, status, error });
}

// ---- Modes ----

async function seed(ctx, io) {
  let code = await io.code('code-X', 'One-time code for device X: both synthetic profiles, hot first, as listed.');
  const X = await enroll(ctx, code, 'X');
  code = null;
  if (X.profileIds.length !== 2) throw new Stop('UNEXPECTED', { step: 'enroll-X', profiles: X.profileIds.length });
  await noteDevice(ctx, X, ['A', 'B']);
  code = await io.code('code-Y', 'One-time code for device Y: only the hot synthetic profile.');
  const Y = await enroll(ctx, code, 'Y');
  code = null;
  if (Y.profileIds.length !== 1 || Y.profileIds[0] !== X.profileIds[0]) throw new Stop('UNEXPECTED', { step: 'enroll-Y', profiles: Y.profileIds.length });
  await noteDevice(ctx, Y, ['A']);
  const corpus = buildCorpus(ctx, { X, Y, A: X.profileIds[0], B: X.profileIds[1], now: Date.now() });
  const limit = ctx.maxBatches ?? Infinity;
  const xs = chunks(corpus.X).slice(0, limit), ys = chunks(corpus.Y).slice(0, limit);
  const plan = [];
  for (let i = 0; i < Math.max(xs.length, ys.length); i++) {
    if (xs[i]) plan.push([X, xs[i]]);
    if (ys[i]) plan.push([Y, ys[i]]);
  }
  ctx.maxRequests = 2 + plan.length + LIMITS.replays;
  // Each status reports the highest seq sent so far, as a device's would.
  const sent = new Map();
  for (const [index, [dev, batch]] of plan.entries()) {
    sent.set(dev, batch.at(-1).seq);
    await step(ctx, `batch-${index + 1}`, dev, batch, batch.map(() => 'accepted'), { status: statusOf(dev, sent.get(dev)) });
  }
  // AC06 (hosted part): the first batch three more times; every ID acknowledged again, and
  // the export check shows each stored once.
  const [dev, batch] = plan[0];
  for (let round = 1; round <= LIMITS.replays; round++) {
    await step(ctx, `replay-${round}`, dev, batch, batch.map(() => 'accepted'), { status: statusOf(dev, sent.get(dev)) });
  }
  if (!ctx.awaitRetention) return;
  // Tokens exist only in this process, so the hosted retention replay happens here: the
  // operator ages exactly batch-1 with the reviewed SQL, waits for one scheduled run, then
  // answers. Aged IDs must come back 'deleted' (never restored) and a live batch 'accepted'.
  ctx.maxRequests += 2;
  const answer = await io.choose('retention', 'Leave this running. After the reviewed aging of batch-1 and one scheduled retention run, type done; type skip to end without the replay.', ['done', 'skip'], LIMITS.retentionWaitMs);
  if (answer === 'skip') { ctx.steps.push({ step: 'retention-replay', skipped: true }); return; }
  await step(ctx, 'retention-aged', dev, batch, batch.map(() => 'deleted'), { status: statusOf(dev, sent.get(dev)) });
  const [live, tail] = plan[1];
  await step(ctx, 'retention-live', live, tail, tail.map(() => 'accepted'), { status: statusOf(live, sent.get(live)) });
}

// The small protocol set: code reuse, a withheld seq, an invalid event, payload and seq
// conflicts, a fresh epoch, shared-profile deletion, an unknown token and device deletion.
async function protocol(ctx, io) {
  let code = await io.code('code-P', 'One-time code for the protocol device: two other synthetic profiles, as listed.');
  const dev = await enroll(ctx, code, 'D');
  if (dev.profileIds.length !== 2) throw new Stop('UNEXPECTED', { step: 'enroll-D', profiles: dev.profileIds.length });
  await noteDevice(ctx, dev, ['P', 'Q']);
  const [P, Q] = dev.profileIds;
  await expectError(ctx, 'code-reuse', await request(ctx, 'enroll', 'POST', '/v1/enroll', { headers: deviceHeaders(ctx), body: JSON.stringify({ code }) }), 400, 'invalid-code');
  code = null;
  const ten = Array.from({ length: 10 }, () => leftEvent(ctx, dev, P));
  await step(ctx, 'gap5', dev, ten.filter(event => event.seq !== 5), Array(9).fill('accepted'));
  const valid = leftEvent(ctx, dev, P, { seq: dev.seq + 1 });
  const bad = { ...valid, family: 'family:6:7:14' };
  if (validateEvent(bad)) throw new Stop('GENERATED_EVENT_INVALID');
  await step(ctx, 'invalid', dev, [bad], ['invalid'], { status: statusOf(dev, dev.seq + 1) });
  const queued = [leftEvent(ctx, dev, Q), leftEvent(ctx, dev, Q)];
  await step(ctx, 'shared', dev, [...queued, leftEvent(ctx, dev, P)], ['accepted', 'accepted', 'accepted']);
  const changed = { ...ten[0], factId: 'sub:13:6', family: CATALOG.facts['sub:13:6'] };
  if (!validateEvent(changed)) throw new Stop('GENERATED_EVENT_INVALID');
  await step(ctx, 'conflict', dev, [changed, leftEvent(ctx, dev, P, { seq: 2 })], ['conflict', 'seq-conflict']);
  dev.epochId = randomUUID();
  dev.seq = 0;
  await step(ctx, 'new-epoch', dev, [leftEvent(ctx, dev, P)], ['accepted']);
  if (ctx.generated > LIMITS.protocolEvents) throw new Stop('EVENT_CAP');
  await io.confirm('delete-profile', 'In the dashboard, export if wanted, then delete only the protocol device\'s Player 2 synthetic profile.');
  await step(ctx, 'profile-deleted', dev, [...queued, leftEvent(ctx, dev, P)], ['deleted', 'deleted', 'accepted']);
  const unknown = `lr1_${dev.token.slice(4, 36)}_${randomBytes(32).toString('base64url')}`;
  ctx.secrets.add(unknown);
  await expectError(ctx, 'unknown-token', await sync(ctx, dev, [], { token: unknown }), 401, 'invalid-credential');
  await io.confirm('delete-device', 'In the dashboard, delete the protocol device (its confirmation lists the affected profiles).');
  await expectError(ctx, 'revoked', await sync(ctx, dev, []), 403, 'revoked');
}

// AC05 expiry: one unused code, exchanged once after its 10-minute lifetime.
async function expiry(ctx, io) {
  let code = await io.code('code-expiry', 'An unused one-time code; it is exchanged once, after 11 minutes.');
  process.stderr.write(`Waiting ${Math.round((ctx.paceMs ?? LIMITS.expiryWaitMs) / 60000)} minutes before the exchange.\n`);
  await sleep(ctx.paceMs ?? LIMITS.expiryWaitMs);
  await expectError(ctx, 'expired-code', await request(ctx, 'enroll', 'POST', '/v1/enroll', { headers: deviceHeaders(ctx), body: JSON.stringify({ code }) }), 400, 'invalid-code');
  code = null;
}

// Offline: compares a dashboard export file with an ID manifest. Reads payloads and labels
// from the export but reports only counts, IDs and hashes. Every ID the manifest shows as
// stored for the profile must appear exactly once, and nothing else; IDs listed with
// --expect-missing (for example the 20 aged by the retention check) must be absent.
async function verifyExport(options) {
  let lines, exported, expectMissing = null;
  try {
    lines = (await readFile(options['--ids'], 'utf8')).split('\n').filter(Boolean).map(line => JSON.parse(line));
    exported = JSON.parse(await readFile(options['--export'], 'utf8'));
    if (options['--expect-missing']) expectMissing = JSON.parse(await readFile(options['--expect-missing'], 'utf8'));
  } catch (error) { throw new Stop('USAGE', { reason: 'unreadable-input' }); }
  const label = options['--profile'];
  const devices = lines.filter(line => line?.kind === 'device');
  const profileId = devices.map(line => line.profiles?.[label]).find(isUuid);
  if (!profileId) throw new Stop('USAGE', { reason: 'profile' });
  if (expectMissing !== null && !(Array.isArray(expectMissing) && expectMissing.every(isUuid))) throw new Stop('USAGE', { reason: 'expect-missing' });
  // Stored state per event ID: accepted stores it, deleted removes it, refusals change nothing.
  const sentProfile = new Map(), stored = new Map();
  for (const line of lines) {
    if (line?.kind === 'sent') for (const event of line.events ?? []) sentProfile.set(event.eventId, event.profile);
    if (line?.kind === 'ack') for (const item of line.results ?? []) {
      if (item.outcome === 'accepted') stored.set(item.eventId, true);
      if (item.outcome === 'deleted') stored.set(item.eventId, false);
    }
  }
  const absent = new Set((expectMissing ?? []).filter(id => sentProfile.get(id) === label));
  const expected = new Set([...stored].filter(([id, kept]) => kept && sentProfile.get(id) === label && !absent.has(id)).map(([id]) => id));
  const items = Array.isArray(exported?.events) ? exported.events : null;
  if (!items || !items.every(item => isRecord(item?.event) && isUuid(item.event.eventId))) throw new Stop('USAGE', { reason: 'export-shape' });
  const ids = items.map(item => item.event.eventId), unique = new Set(ids);
  const missing = [...expected].filter(id => !unique.has(id)).sort();
  const counts = {
    exported: ids.length, duplicates: ids.length - unique.size, foreignProfile: items.filter(item => item.event.profileId !== profileId).length,
    expected: expected.size, matched: [...unique].filter(id => expected.has(id)).length, missing: missing.length,
    unexpected: [...unique].filter(id => !expected.has(id) && !absent.has(id)).length, missingSetSha256: sha(missing.join('\n')),
    expectedAbsent: absent.size, expectedAbsentPresent: [...absent].filter(id => unique.has(id)).length,
  };
  const passed = counts.duplicates === 0 && counts.foreignProfile === 0 && counts.unexpected === 0 && counts.missing === 0 && counts.expectedAbsentPresent === 0;
  return { passed, counts, missingIds: missing.slice(0, 50) };
}

// ---- Operator input ----

// Reads one line from stdin only while a prompt is waiting. Input that arrives earlier
// (piped in advance, typed ahead) stops the run instead of being used. On a terminal the
// code is not echoed.
function stdinReader(ctx) {
  const input = process.stdin;
  let waiter = null, buffer = '', early = false, ended = false, timer = null, raw = false;
  const finish = (error, value) => {
    clearTimeout(timer);
    if (raw) { input.setRawMode(false); raw = false; }
    const current = waiter;
    waiter = null;
    buffer = '';
    if (current) error ? current.reject(error) : current.resolve(value);
  };
  const onData = chunk => {
    if (!waiter) { early = true; return; }
    const text = String(chunk);
    for (let i = 0; i < text.length; i++) {
      const ch = text[i];
      if (ch === '\u0003') return finish(new Stop('INTERRUPTED'));
      if (ch === '\r' || ch === '\n') {
        if (text.slice(i + 1).replace(/^\n/, '').length) early = true;
        return finish(null, buffer);
      }
      buffer = ch === '\u007f' || ch === '\b' ? buffer.slice(0, -1) : buffer + ch;
      if (buffer.length > 200) return finish(new Stop('INPUT_TOO_LONG'));
    }
  };
  input.setEncoding('utf8');
  input.on('data', onData);
  input.on('end', () => { ended = true; finish(new Stop('INPUT_CLOSED')); });
  const settled = sleep(200);
  async function read(name, prompt, secret, timeoutMs = LIMITS.inputWaitMs) {
    await settled;
    if (early) throw new Stop('INPUT_BEFORE_PROMPT');
    if (ended) throw new Stop('INPUT_CLOSED');
    if (secret && input.isTTY) { input.setRawMode(true); raw = true; }
    process.stderr.write(`WAITING:${name} ${prompt}\n`);
    return new Promise((resolveLine, reject) => {
      waiter = { resolve: resolveLine, reject };
      timer = setTimeout(() => finish(new Stop('INPUT_TIMEOUT', { name })), timeoutMs);
    });
  }
  return {
    async code(name, prompt) {
      const line = await read(name, prompt, true);
      const code = normalizeCode(line);
      for (const value of [line, line.trim(), code, code.match(/.{1,4}/g)?.join('-')]) if (value) ctx.secrets.add(value);
      if (!CODE.test(code)) throw new Stop('CODE_FORMAT');
      return code;
    },
    async confirm(name, prompt) {
      if ((await read(name, `${prompt} Then type done and press Enter.`, false)).trim() !== 'done') throw new Stop('NOT_CONFIRMED', { name });
    },
    async choose(name, prompt, choices, timeoutMs) {
      const answer = (await read(name, prompt, false, timeoutMs)).trim();
      if (!choices.includes(answer)) throw new Stop('NOT_CONFIRMED', { name });
      return answer;
    },
    close() { clearTimeout(timer); input.off('data', onData); input.destroy(); },
  };
}

// Refuses to write or print anything containing a code or token seen in this run.
function guard(ctx, text) {
  for (const secret of ctx?.secrets ?? []) if (secret.length >= 8 && text.includes(secret)) throw new Stop('LEAK_GUARD');
  if (/lr1_[0-9a-f]{32}_/.test(text)) throw new Stop('LEAK_GUARD');
  return text;
}

// ---- Run ----

export async function run(argv) {
  const runId = randomUUID(), startedAt = new Date().toISOString();
  let options = null, ctx = null, io = null, out = null, receipt = null, exit = 0;
  try {
    options = parseArgs(argv);
    out = await outputDir(options['--out']);
    receipt = {
      tool: 'learning-reporting hosted-check', schemaVersion: 1, runId, mode: options.mode, startedAt,
      toolSha256: sha(await readFile(SELF)), contractSha256: sha(await readFile(CONTRACT)), limitations: LIMITATIONS,
    };
    if (options.mode === 'verify-export') {
      const result = await verifyExport(options);
      Object.assign(receipt, { profile: options['--profile'], counts: result.counts, missingIds: result.missingIds });
      if (!result.passed) throw new Stop('EXPORT_MISMATCH');
    } else {
      const { manifest, manifestSha256, budget } = await loadManifest(options, Date.now());
      ctx = {
        target: manifest.target, gameOrigin: manifest.gameOrigin, phase: manifest.phase, loopback: options.loopback,
        paceMs: options.loopback ? options['--loopback-pace-ms'] ?? null : null, maxBatches: options.loopback ? options['--loopback-max-batches'] ?? null : null,
        awaitRetention: options['--await-retention'] === true,
        maxRequests: REQUEST_CAPS[options.mode] ?? 2, last: {}, requests: 0, generated: 0, steps: [], outcomes: {}, ids: new Set(),
        profiles: {}, secrets: new Set(), idsFile: resolve(out, `ids-${options.mode}-${runId}.jsonl`),
      };
      Object.assign(receipt, {
        manifestSha256, targetSha256: sha(manifest.target), gameOriginSha256: sha(manifest.gameOrigin), phase: manifest.phase,
        expected: { sourceCommit: manifest.expected.sourceCommit, workerVersion: manifest.expected.workerVersion, configSha256: manifest.expected.configSha256 },
        loopbackToolTest: options.loopback, budget,
      });
      if (options.mode === 'probe') await probe(ctx);
      else {
        await writeFile(ctx.idsFile, `${JSON.stringify({ kind: 'run', runId, mode: options.mode, targetSha256: receipt.targetSha256 })}\n`, { mode: 0o600, flag: 'wx' });
        receipt.ids = basename(ctx.idsFile);
        io = stdinReader(ctx);
        await { seed, protocol, expiry }[options.mode](ctx, io);
      }
    }
    receipt.result = 'passed';
  } catch (error) {
    const stop = error instanceof Stop ? error : new Stop('INTERNAL', { name: word(String(error?.name ?? 'error').toLowerCase()) });
    exit = USAGE.has(stop.code) ? 2 : 1;
    if (receipt) Object.assign(receipt, { result: 'stopped', stop: { code: stop.code, detail: clean(stop.detail) } });
    else receipt = { result: 'stopped', stop: { code: stop.code, detail: clean(stop.detail) } };
  } finally {
    io?.close();
  }
  if (ctx) Object.assign(receipt, {
    finishedAt: new Date().toISOString(), requests: ctx.requests, generatedEvents: ctx.generated, outcomes: ctx.outcomes,
    uniqueEventIds: ctx.ids.size, idSetSha256: sha([...ctx.ids].sort().join('\n')), steps: ctx.steps,
  });
  let file = null;
  try {
    if (out && receipt.tool) {
      file = resolve(out, `receipt-${receipt.mode}-${runId}.json`);
      await writeFile(file, `${guard(ctx, JSON.stringify(receipt, null, 2))}\n`, { mode: 0o600, flag: 'wx' });
    }
  } catch (error) {
    file = null;
    exit = 1;
    receipt = { result: 'stopped', stop: { code: error instanceof Stop ? error.code : 'RECEIPT_WRITE', detail: {} } };
  }
  const summary = { ok: exit === 0, mode: options?.mode ?? null, runId, result: receipt.result, stop: receipt.stop ?? null,
    requests: ctx?.requests ?? 0, outcomes: ctx?.outcomes ?? {}, receipt: file ? basename(file) : null, ids: receipt.ids ?? null };
  let line;
  try { line = guard(ctx, JSON.stringify(summary)); } catch (error) { line = JSON.stringify({ ok: false, runId, stop: { code: 'LEAK_GUARD' } }); exit = 1; }
  process.stdout.write(`${line}\n`);
  ctx?.secrets.clear();
  return exit;
}

if (process.argv[1] && resolve(process.argv[1]) === SELF) process.exitCode = await run(process.argv.slice(2));
